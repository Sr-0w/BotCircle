// Builds the file-format icons used by the Web and Android clients from Seti UI (MIT, © Jesse Weed,
// https://github.com/jesseweed/seti-ui). Only a subset is embedded, as path data, so nothing is fetched at runtime.
//
//   npm pack seti-ui@1.11.0 && tar -xzf seti-ui-1.11.0.tgz
//   node tools/file-icons/generate.mjs ./package
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) { console.error('usage: generate.mjs <seti-ui package dir>'); process.exit(1); }
const vars = Object.fromEntries([...readFileSync(join(root, 'styles/ui-variables.less'), 'utf8').matchAll(/^@([\w-]+):\s*(#[0-9a-fA-F]{6});/gm)].map((m) => [m[1], m[2]]));
const mapping = readFileSync(join(root, 'styles/components/icons/mapping.less'), 'utf8');

// Formats people actually exchange in a conversation; anything else gets the generic icon.
const WANTED = new Set(('py js mjs cjs jsx ts tsx mts json jsonc md markdown mdx txt csv tsv log html htm css scss sass less sh bash zsh fish ps1 go rs java kt kts c h cpp cc hpp cs rb php swift dart lua r sql db sqlite yml yaml xml toml ini cfg conf env lock pdf png jpg jpeg gif webp svg ico bmp zip tar gz tgz 7z rar mp3 wav ogg flac m4a mp4 mov webm mkv avi doc docx xls xlsx ppt pptx ipynb tex vue svelte graphql gql gradle tf ex exs erl hs scala clj zig nim').split(' '));
const NAMES = new Set(['Dockerfile', 'Makefile', 'docker-compose.yml', 'docker-compose.yaml', 'package.json', '.gitignore', 'LICENSE', 'README.md']);

const byKey = {};
for (const m of mapping.matchAll(/\.icon-(?:set|partial)\(\s*["']([^"']+)["']\s*,\s*["']([^"']+)["']\s*,\s*@([\w-]+)\s*\)/g)) {
  const [, key, icon, color] = m;
  const ext = key.startsWith('.') ? key.slice(1).toLowerCase() : null;
  if ((ext && WANTED.has(ext)) || NAMES.has(key)) byKey[ext ?? key] ??= { icon, color: vars[color] ?? vars.white };
}
// Formats Seti files under a generic icon.
for (const [ext, icon, color] of [['ppt', 'default', 'orange'], ['pptx', 'default', 'orange'], ['7z', 'zip', 'grey-light'], ['rar', 'zip', 'grey-light'], ['tgz', 'zip', 'grey-light'], ['gz', 'zip', 'grey-light'], ['tar', 'zip', 'grey-light'], ['webm', 'video', 'pink'], ['mkv', 'video', 'pink'], ['flac', 'audio', 'purple'], ['m4a', 'audio', 'purple'], ['log', 'default', 'grey-light'], ['env', 'config', 'grey-light'], ['sqlite', 'db', 'pink'], ['db', 'db', 'pink']]) byKey[ext] ??= { icon, color: vars[color] };

const icons = {};
for (const icon of new Set([...Object.values(byKey).map((v) => v.icon), 'default'])) {
  const svg = readFileSync(join(root, 'icons', `${icon}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no path in ${icon}`);
  icons[icon] = paths.join(' ');
}
const header = '// Generated by tools/file-icons/generate.mjs from Seti UI 1.11.0 (MIT, © Jesse Weed). Do not edit.';
const entries = Object.entries(byKey).sort(([a], [b]) => a.localeCompare(b));

writeFileSync('apps/web/src/lib/file-icons.generated.ts', `${header}
/** Seti icon path data (viewBox 0 0 32 32), by icon name. */
export const SETI_PATHS: Record<string, string> = ${JSON.stringify(icons, null, 1)};
/** File extension (or exact file name) → [icon, colour]. */
export const SETI_FILES: Record<string, [string, string]> = ${JSON.stringify(Object.fromEntries(entries.map(([k, v]) => [k, [v.icon, v.color]])), null, 1)};
`);

const kt = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
writeFileSync('apps/android/app/src/main/kotlin/app/dot/opendots/ui/FileIconsGenerated.kt', `${header}
package app.dot.opendots.ui

/** Seti icon path data (viewBox 0 0 32 32), by icon name. */
internal val SETI_PATHS: Map<String, String> = mapOf(
${Object.entries(icons).map(([k, v]) => `    ${kt(k)} to ${kt(v)},`).join('\n')}
)

/** File extension (or exact file name) → icon and colour (ARGB). */
internal val SETI_FILES: Map<String, Pair<String, Long>> = mapOf(
${entries.map(([k, v]) => `    ${kt(k)} to (${kt(v.icon)} to 0xFF${v.color.slice(1).toUpperCase()}),`).join('\n')}
)
`);
console.log(`${entries.length} names → ${Object.keys(icons).length} icons, ${Object.values(icons).reduce((n, p) => n + p.length, 0)} bytes of path data`);
